#!/usr/bin/env python3
"""Bakes country outlines from Natural Earth into a Dart file.

    python3 tool/maps.py /path/to/ne_50m_admin_0_countries.geojson example/lib/map_data.dart

Natural Earth is public domain (https://www.naturalearthdata.com). This keeps
the countries between Iceland and the Urals and down to the Cape, simplifies
each outline (Douglas-Peucker, coarser for large countries), clamps what runs
off the area to its edge, and writes them as longitude/latitude rings, so a
composition draws maps with no data file to load.
"""

import json
import math
import sys

LON = (-32.0, 75.0)
LAT = (-38.0, 74.0)
# Countries the videos zoom into keep more detail.
DETAIL = {"Ukraine": 0.03, "Tanzania": 0.04, "Israel": 0.02, "France": 0.05, "Botswana": 0.06, "Namibia": 0.06}


def perp(p, a, b):
    (x, y), (x1, y1), (x2, y2) = p, a, b
    dx, dy = x2 - x1, y2 - y1
    if dx == 0 and dy == 0:
        return math.hypot(x - x1, y - y1)
    t = max(0, min(1, ((x - x1) * dx + (y - y1) * dy) / (dx * dx + dy * dy)))
    return math.hypot(x - (x1 + t * dx), y - (y1 + t * dy))


def simplify(points, tol):
    if len(points) < 3:
        return points
    keep = [False] * len(points)
    keep[0] = keep[-1] = True
    stack = [(0, len(points) - 1)]
    while stack:
        i, j = stack.pop()
        far, at = 0.0, None
        for k in range(i + 1, j):
            d = perp(points[k], points[i], points[j])
            if d > far:
                far, at = d, k
        if at is not None and far > tol:
            keep[at] = True
            stack += [(i, at), (at, j)]
    return [p for p, k in zip(points, keep) if k]


def area(ring):
    return abs(sum(ring[i][0] * ring[(i + 1) % len(ring)][1] - ring[(i + 1) % len(ring)][0] * ring[i][1] for i in range(len(ring)))) / 2


def main():
    src, dst = sys.argv[1], sys.argv[2]
    data = json.load(open(src))
    out = {}
    for f in data["features"]:
        name = f["properties"]["NAME"]
        g = f["geometry"]
        polys = g["coordinates"] if g["type"] == "MultiPolygon" else [g["coordinates"]]
        rings = []
        for poly in polys:
            ring = poly[0]
            xs = [p[0] for p in ring]
            ys = [p[1] for p in ring]
            if max(xs) < LON[0] or min(xs) > LON[1] or max(ys) < LAT[0] or min(ys) > LAT[1]:
                continue
            ring = [(min(max(x, LON[0]), LON[1]), min(max(y, LAT[0]), LAT[1])) for x, y in ring]
            tol = DETAIL.get(name, 0.12 if area(ring) < 40 else 0.18)
            ring = simplify(ring, tol)
            if len(ring) >= 4 and area(ring) > 0.02:
                rings.append(ring)
        if rings:
            out[name] = rings
    lines = [
        "// Generated by tool/maps.py from Natural Earth 1:50m countries (public domain).",
        "// Do not edit: run the tool again.",
        "",
        "/// Country outlines as rings of longitude, latitude, longitude, latitude...",
        "const Map<String, List<List<double>>> mapCountries = <String, List<List<double>>>{",
    ]
    for name in sorted(out):
        rings = ", ".join("<double>[" + ", ".join(f"{x:.2f}, {y:.2f}" for x, y in r) + "]" for r in out[name])
        lines.append(f"  {json.dumps(name)}: <List<double>>[{rings}],")
    lines.append("};")
    open(dst, "w").write("\n".join(lines) + "\n")
    print(f"{len(out)} countries, {sum(len(r) for rs in out.values() for r in rs)} points")


main()
